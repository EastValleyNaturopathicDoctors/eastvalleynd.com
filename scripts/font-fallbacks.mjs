/**
 * Generate metric-matched fallback faces, so the moment the real font lands
 * nothing on the page moves.
 *
 * The web fonts are self-hosted and preloaded, but on a slow connection the
 * inlined stylesheet now paints the page *before* the font file arrives. The
 * browser draws the hero in the fallback, then swaps — and because Arial and
 * Bricolage Grotesque have different widths and vertical metrics, the swap
 * shifted hero-sub, hero-meta and hero-cta by 0.03 CLS on Slow 4G.
 *
 * capsize computes `size-adjust`, `ascent-override`, `descent-override` and
 * `line-gap-override` for a local fallback so its lines occupy the same space
 * as the target face. The numbers are derived from published font metrics,
 * not tuned by eye. Output: src/styles/font-fallbacks.css. Re-run if a font
 * changes: `node scripts/font-fallbacks.mjs`.
 */
import { createFontStack } from '@capsizecss/core';
import bricolage from '@capsizecss/metrics/bricolageGrotesque';
import manrope from '@capsizecss/metrics/manrope';
import arial from '@capsizecss/metrics/arial';
import { writeFile } from 'node:fs/promises';

const stacks = [
  // The names must match what fontsource registers, or the browser never
  // reaches the fallback rule for the right family.
  { face: { ...bricolage, familyName: 'Bricolage Grotesque Variable' }, fallback: arial },
  { face: manrope, fallback: arial },
];

let css = '/* GENERATED by scripts/font-fallbacks.mjs — do not hand-edit. */\n';
const families = [];
for (const { face, fallback } of stacks) {
  const { fontFamily, fontFaces } = createFontStack([face, fallback]);
  families.push(fontFamily);
  css += `\n/* ${face.familyName} -> ${fallback.familyName}, metric-matched */\n${fontFaces}\n`;
}
await writeFile('src/styles/font-fallbacks.css', css);
console.log(css);
console.log('font-family stacks to use:');
for (const f of families) console.log('  ' + f);
